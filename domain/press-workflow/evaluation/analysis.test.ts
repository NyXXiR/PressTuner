import { buildReport } from "./report";
import { analyseQuality, pairedInterval, wilson } from "./analysis";

test("Wilson handles absent denominators and uncertainty at zero/all events", () => {
  assert.equal(wilson(0, 0), null);
  assert.ok(wilson(0, 10)!.high > .27);
  assert.ok(wilson(10, 10)!.low < .73);
  assert.throws(() => wilson(11, 10));
});
test("paired analysis never treats repetitions as independent or tiny samples as proof", () => {
  assert.equal(pairedInterval([.1]).state, "INSUFFICIENT_GROUPS");
  assert.equal(pairedInterval(Array(10).fill(.1)).state, "DEGENERATE");
  const values = Array.from({ length: 12 }, (_, i) => i / 100);
  const a = pairedInterval(values);
  assert.equal(a.state, "EXPLORATORY");
  assert.deepEqual(a, pairedInterval(values));
  assert.ok(a.interval!.low < a.meanDelta! && a.interval!.high > a.meanDelta!);
});

test("real saved review yields evaluator and unsupported promotion recommendations without invented improvement", async () => {
  const dataset = datasetSchema.parse(JSON.parse(await readFile("evals/press-workflow/dual/v1/dataset.json", "utf8")));
  // The portable fixture is generated by the test setup from the historical artifact without human identity.
  const fixture = JSON.parse(await readFile(new URL("./analysis-fixture.json", import.meta.url), "utf8"));
  const batch = evaluationBundleSchema.parse(fixture.batch);
  const report = buildReport(dataset, batch, fixture.review);
  assert.equal(report.insights.paired[0].state, "INSUFFICIENT_GROUPS");
  assert.ok(report.insights.recommendations.some(r => r.code === "REPAIR_EVALUATOR" && r.count === 1));
  assert.ok(report.insights.recommendations.some(r => r.code === "GROUND_CLAIMS" && r.confidence === "HUMAN_CONFIRMED"));
  assert.ok(!JSON.stringify(report.summary).includes(fixture.review.reviewer.id));
  assert.ok(!JSON.stringify(report.summary).includes(batch.evaluations[0].draft.text));
});

test("failed attempts and correlated repetitions cannot inflate group counts", async () => {
  const fixture = JSON.parse(await readFile(new URL("./analysis-fixture.json", import.meta.url), "utf8"));
  const batch: EvaluationBundle = fixture.batch;
  const b = structuredClone(batch);
  b.generation.attempts.push({ ...b.generation.attempts[0], trial: 2, draft: null, errorCode: "GENERATION_FAILED" });
  const a = analyseQuality(b, []);
  const support = a.rates.find(r => r.variant === "BASELINE" && r.criterion === "FACTUAL_SUPPORT")!;
  assert.equal(support.groupCount, 1);
  assert.equal(support.unknownGroups, 1);
  assert.equal(support.interval, null);
  assert.equal(a.paired[0].completeGroups, 0);
});

test("a source with only failed generations remains unknown, not an empty successful sample", async () => {
  const fixture = JSON.parse(await readFile(new URL("./analysis-fixture.json", import.meta.url), "utf8"));
  const dataset = datasetSchema.parse(JSON.parse(await readFile("evals/press-workflow/dual/v1/dataset.json", "utf8")));
  const batch: EvaluationBundle = fixture.batch;
  batch.evaluations = [];
  batch.generation.attempts.forEach(a => { a.draft = null; a.errorCode = "GENERATION_FAILED"; });
  const report = buildReport(dataset, batch);
  assert.equal(report.insights.rates[0].unknownGroups, 1);
  assert.equal(report.insights.paired[0].excludedGroups, 1);
  assert.equal(report.insights.paired[0].meanDelta, null);
  assert.ok(report.insights.recommendations.some(r => r.code === "REPAIR_GENERATION" && r.count === 2));
});

test("cluster pairing is invariant to identical repeats within each source", async () => {
  const fixture = JSON.parse(await readFile(new URL("./analysis-fixture.json", import.meta.url), "utf8"));
  const batch: EvaluationBundle = fixture.batch;
  const groupBatch = structuredClone(batch);
  groupBatch.evaluations = []; groupBatch.generation.attempts = [];
  for (let i = 1; i <= 12; i++) {
    for (const e of batch.evaluations) {
      const copy = structuredClone(e);
      copy.draft.caseId = `C${String(i).padStart(2, "0")}`; copy.draft.groupId = `independent-test-${i}`;
      copy.ragas.score = copy.draft.variant === "BASELINE" ? .5 : .5 + i / 100;
      groupBatch.evaluations.push(copy);
      groupBatch.generation.attempts.push({ caseId: copy.draft.caseId, variant: copy.draft.variant, trial: 1, draft: copy.draft, errorCode: null });
    }
  }
  const first = analyseQuality(groupBatch, []).paired[0];
  const extra = groupBatch.evaluations.map(e => { const copy = structuredClone(e); copy.draft.trial = 2; return copy; });
  groupBatch.evaluations.push(...extra);
  groupBatch.generation.attempts.push(...extra.map(e => ({ caseId: e.draft.caseId, variant: e.draft.variant, trial: 2, draft: e.draft, errorCode: null })));
  const repeated = analyseQuality(groupBatch, []).paired[0];
  assert.equal(first.completeGroups, 12);
  assert.equal(repeated.pairCount, 24);
  assert.deepEqual(first.interval, repeated.interval);
  assert.equal(first.meanDelta, repeated.meanDelta);
});
